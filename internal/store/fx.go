// fxNetSpent 는 asOf 다음 날부터 today 까지 외화를 사느라 통장에서 나간 원화 − 팔아서 들어온 원화.
// 처음 잔고는 통장에서 나간 돈이 아니므로 뺀다.
func (s *Store) fxNetSpent(asOf, today string) (int64, error) {
	var buy, sell int64
	err := s.queryRow(`
SELECT COALESCE(SUM(krw) FILTER (WHERE side='buy' AND source <> 'opening'), 0),
       COALESCE(SUM(krw) FILTER (WHERE side='sell'), 0)
FROM fx_trades WHERE date > ? AND date <= ?`, asOf, today).Scan(&buy, &sell)
	return buy - sell, err
}

// fxBlockDays 는 매일 모으기 출금을 묶는 날 수(자금 계획 일정이 매일 한 줄씩 늘어나지 않게).
const fxBlockDays = 7

// fxCashEvents 는 앞으로 매일 모으기로 나갈 원화를 7일씩 묶은 출금. 묶음의 첫날에 한꺼번에 빠진다고
// 보아(조금 이르게) 잔액을 넉넉히 보지 않는다. 목표 환율 매수는 언제 될지 몰라 넣지 않는다.
func fxCashEvents(plans []FxPlan, rates fxRateBook, today, horizon time.Time) []CashEvent {
	type day struct {
		krw int64
		est bool
	}
	byDate := map[string]*day{}
	todayStr, horizonStr := fmtDay(today), fmtDay(horizon)
	for _, p := range plans {
		if !p.Active || p.Kind != "daily" || p.DoneAt != "" {
			continue
		}
		c, ok := FxCurrencyOf(p.Currency)
		if !ok {
			continue
		}
		rate, _, _ := rates.latest(p.Currency)
		if p.Unit == "fx" && rate <= 0 {
			continue
		}
		from := todayStr
		if p.StartDate > from {
			from = p.StartDate
		}
		if p.LastRun >= from {
			d, _ := time.Parse(dateLayout, p.LastRun)
			from = fmtDay(d.AddDate(0, 0, 1))
		}
		to := horizonStr
		if p.EndDate != "" && p.EndDate < to {
			to = p.EndDate
		}
		_, krw := planAmounts(p, c, rate)
		d, err := time.Parse(dateLayout, from)
		if err != nil {
			continue
		}
		for ; fmtDay(d) <= to; d = d.AddDate(0, 0, 1) {
			if p.WeekdaysOnly && isWeekend(d) {
				continue
			}
			x := byDate[fmtDay(d)]
			if x == nil {
				x = &day{}
				byDate[fmtDay(d)] = x
			}
			x.krw += krw
			x.est = x.est || p.Unit == "fx"
		}
	}
	if len(byDate) == 0 {
		return nil
	}
	var out []CashEvent
	for start := today; !start.After(horizon); start = start.AddDate(0, 0, fxBlockDays) {
		var sum int64
		var est bool
		first, n := "", 0
		for i := 0; i < fxBlockDays; i++ {
			ds := fmtDay(start.AddDate(0, 0, i))
			if ds > horizonStr {
				break
			}
			if x := byDate[ds]; x != nil && x.krw > 0 {
				if first == "" {
					first = ds
				}
				sum += x.krw
				est = est || x.est
				n++
			}
		}
		if sum > 0 {
			out = append(out, CashEvent{
				Date: first, Kind: "fx", Label: fmt.Sprintf("외화 매일 모으기 %d일치", n),
				Amount: -sum, Estimated: est,
			})
		}
	}
	return out
}


// 앱이 실제로 사고팔지는 않는다. 사용자가 적은 사기·팔기와, 매일 모으기·목표 환율 매수 계획을 앱이
// 그날 환율로 자동 기록한 매수(추정)로 통화별 보유량·평균 매입 환율·평가손익을 낸다.
// 외화를 산 원화는 통장에서 빠진 돈이라 자금 계획의 현재 잔액과 앞으로의 출금에도 넣는다.
//
// 금액 단위
//   - 외화 금액은 통화의 최소 단위 정수(달러는 센트, 엔·동·루피아는 1). FxCurrency.Decimals 참고.
//   - 원화는 원 단위 정수.
//   - 환율은 외화 1단위(1달러·1엔)당 원화(실수). 화면은 엔·동·루피아를 100단위로 보여 준다.


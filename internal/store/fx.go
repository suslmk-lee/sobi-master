// FxPosition 은 통화 하나의 보유 현황.
type FxPosition struct {
	Currency string  `json:"currency"`
	Amount   int64   `json:"amount"`   // 보유 외화(최소 단위)
	Cost     int64   `json:"cost"`     // 남은 보유분을 사는 데 든 원화(평균 매입가 기준)
	AvgRate  float64 `json:"avgRate"`  // 평균 매입 환율
	Rate     float64 `json:"rate"`     // 지금 환율(없으면 0)
	RateDate string  `json:"rateDate"` // 지금 환율의 날짜
	Value    int64   `json:"value"`    // 지금 환율로 본 원화 가치
	// Unrealized 는 평가손익(Value − Cost), Realized 는 판 외화에서 생긴 손익 합.
	Unrealized int64 `json:"unrealized"`
	Realized   int64 `json:"realized"`
	Bought     int64 `json:"bought"` // 산 원화 합(처음 잔고 포함)
	Sold       int64 `json:"sold"`   // 판 원화 합
	Trades     int   `json:"trades"`
}

// buildFxPositions 는 거래를 날짜순으로 쌓아 통화별 보유 현황을 낸다(평균 매입가 방식).
func buildFxPositions(trades []FxTrade, rates fxRateBook) map[string]*FxPosition {
	sorted := append([]FxTrade(nil), trades...)
	sort.SliceStable(sorted, func(i, j int) bool {
		if sorted[i].Date != sorted[j].Date {
			return sorted[i].Date < sorted[j].Date
		}
		if sorted[i].Side != sorted[j].Side {
			return sorted[i].Side == "buy"
		}
		return sorted[i].ID < sorted[j].ID
	})
	out := map[string]*FxPosition{}
	for _, t := range sorted {
		p := out[t.Currency]
		if p == nil {
			p = &FxPosition{Currency: t.Currency}
			out[t.Currency] = p
		}
		p.Trades++
		if t.Side == "buy" {
			p.Amount += t.Amount
			p.Cost += t.KRW
			p.Bought += t.KRW
			continue
		}
		p.Sold += t.KRW
		if p.Amount <= 0 {
			continue
		}
		sell := t.Amount
		if sell > p.Amount {
			sell = p.Amount
		}
		costOut := int64(math.Round(float64(p.Cost) * float64(sell) / float64(p.Amount)))
		p.Realized += t.KRW - costOut
		p.Cost -= costOut
		p.Amount -= sell
	}
	for cur, p := range out {
		c, _ := FxCurrencyOf(cur)
		if p.Amount > 0 {
			p.AvgRate = float64(p.Cost) / fxMajor(c, p.Amount)
		} else {
			p.Cost = 0
		}
		p.Rate, p.RateDate, _ = rates.latest(cur)
		if p.Rate > 0 {
			p.Value = fxKRW(c, p.Amount, p.Rate)
			p.Unrealized = p.Value - p.Cost
		}
	}
	return out
}

// FxRateRow 는 환율 표 한 줄.
type FxRateRow struct {
	Currency string  `json:"currency"`
	Rate     float64 `json:"rate"` // 외화 1단위당 원화(0 이면 아직 모름)
	Prev     float64 `json:"prev"` // 그 전 날짜의 환율(0 이면 없음)
	Date     string  `json:"date"`
}

// FxPlanStatus 는 계획 하나와 지금까지의 실행 결과.
type FxPlanStatus struct {
	Plan   FxPlan `json:"plan"`
	Count  int    `json:"count"`  // 기록된 매수 횟수
	Spent  int64  `json:"spent"`  // 쓴 원화
	Bought int64  `json:"bought"` // 산 외화(최소 단위)
	// Rate 는 지금 환율, Hit 는 목표 매수 조건(지금 환율 ≤ 목표)이 맞는지.
	Rate float64 `json:"rate"`
	Hit  bool    `json:"hit"`
	// DailyKRW 는 매일 모으기 하루 원화(외화 금액 계획은 지금 환율로 환산).
	DailyKRW int64 `json:"dailyKrw"`
}


// ---- 환율 ----

type fxRatePoint struct {
	Date string
	Rate float64
}

// fxRateBook 은 통화별 날짜순 환율.
type fxRateBook map[string][]fxRatePoint

// on 은 date 의 환율: 그날 또는 그 전 가장 가까운 날의 값. 그 전 값이 하나도 없으면 그 뒤 가장 가까운
// 값(앱을 쓰기 시작한 날보다 이른 날). 값이 아예 없으면 ok=false.
func (b fxRateBook) on(cur, date string) (rate float64, rateDate string, ok bool) {
	pts := b[cur]
	i := sort.Search(len(pts), func(i int) bool { return pts[i].Date > date })
	if i > 0 {
		return pts[i-1].Rate, pts[i-1].Date, true
	}
	if len(pts) > 0 {
		return pts[0].Rate, pts[0].Date, true
	}
	return 0, "", false
}

// latest 는 가장 최근 환율과 그 전날(값이 있는 이전 날짜)의 환율.
func (b fxRateBook) latest(cur string) (rate float64, date string, prev float64) {
	pts := b[cur]
	if len(pts) == 0 {
		return 0, "", 0
	}
	last := pts[len(pts)-1]
	if len(pts) > 1 {
		prev = pts[len(pts)-2].Rate
	}
	return last.Rate, last.Date, prev
}

func (s *Store) fxRateBook() (fxRateBook, error) {
	rows, err := s.query(`SELECT currency, date, rate FROM fx_rates ORDER BY currency, date`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	b := fxRateBook{}
	for rows.Next() {
		var cur string
		var p fxRatePoint
		if err := rows.Scan(&cur, &p.Date, &p.Rate); err != nil {
			return nil, err
		}
		b[cur] = append(b[cur], p)
	}
	return b, rows.Err()
}

// SaveFxRates 는 date 날의 환율(외화 1단위당 원화)을 저장한다. 같은 날 값은 새 값으로 바꾼다.
func (s *Store) SaveFxRates(date string, rates map[string]float64, source string) error {
	if _, err := time.Parse(dateLayout, date); err != nil {
		return fmt.Errorf("환율 날짜 형식: %s", date)
	}
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	for cur, r := range rates {
		if _, ok := FxCurrencyOf(cur); !ok || r <= 0 || math.IsNaN(r) || math.IsInf(r, 0) {
			continue
		}
		if _, err := tx.Exec(pq(`
INSERT INTO fx_rates(date, currency, rate, source) VALUES(?,?,?,?)
ON CONFLICT (date, currency) DO UPDATE SET rate = excluded.rate, source = excluded.source`),
			date, cur, r, source); err != nil {
			return err
		}
	}
	return tx.Commit()
}


// fxPlanLabel 은 계획을 짧게 부르는 이름("USD 매일 모으기").
func fxPlanLabel(p FxPlan) string {
	if p.Kind == "target" {
		return p.Currency + " 목표 환율 매수"
	}
	return p.Currency + " 매일 모으기"
}

// GetFxOverview 는 외화 화면에 필요한 것을 한 번에 모은다.
func (s *Store) GetFxOverview() (FxOverview, error) {
	out := FxOverview{
		Currencies: FxCurrencies, Rates: []FxRateRow{}, Positions: []FxPosition{},
		Plans: []FxPlanStatus{}, Trades: []FxTrade{}, PlanNames: map[int64]string{},
	}
	rates, err := s.fxRateBook()
	if err != nil {
		return out, err
	}
	for _, c := range FxCurrencies {
		r, d, prev := rates.latest(c.Code)
		out.Rates = append(out.Rates, FxRateRow{Currency: c.Code, Rate: r, Prev: prev, Date: d})
		if d > out.RateDate {
			out.RateDate = d
		}
	}
	trades, err := s.ListFxTrades()
	if err != nil {
		return out, err
	}
	pos := buildFxPositions(trades, rates)
	for _, c := range FxCurrencies {
		if p := pos[c.Code]; p != nil {
			out.Positions = append(out.Positions, *p)
			out.Value += p.Value
			out.Cost += p.Cost
			out.Unrealized += p.Unrealized
			out.Realized += p.Realized
		}
	}
	plans, err := s.ListFxPlans()
	if err != nil {
		return out, err
	}
	byPlan := map[int64]*FxPlanStatus{}
	for _, p := range plans {
		st := FxPlanStatus{Plan: p}
		st.Rate, _, _ = rates.latest(p.Currency)
		st.Hit = p.Kind == "target" && st.Rate > 0 && st.Rate <= p.TargetRate
		if p.Kind == "daily" {
			c, _ := FxCurrencyOf(p.Currency)
			_, st.DailyKRW = planAmounts(p, c, st.Rate)
		}
		out.Plans = append(out.Plans, st)
		out.PlanNames[p.ID] = fxPlanLabel(p)
	}
	for i := range out.Plans {
		byPlan[out.Plans[i].Plan.ID] = &out.Plans[i]
	}
	for _, t := range trades {
		if t.PlanID != nil {
			if st := byPlan[*t.PlanID]; st != nil {
				st.Count++
				st.Spent += t.KRW
				st.Bought += t.Amount
			}
		}
	}
	for i := len(trades) - 1; i >= 0; i-- {
		out.Trades = append(out.Trades, trades[i])
	}
	return out, nil
}


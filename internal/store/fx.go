// FxCurrencyOf 는 통화 코드의 정보.
func FxCurrencyOf(code string) (FxCurrency, bool) {
	for _, c := range FxCurrencies {
		if c.Code == code {
			return c, true
		}
	}
	return FxCurrency{}, false
}

func pow10(n int) int64 {
	p := int64(1)
	for i := 0; i < n; i++ {
		p *= 10
	}
	return p
}

// fxMajor 는 최소 단위 금액을 통화 단위(달러) 실수로.
func fxMajor(c FxCurrency, minor int64) float64 { return float64(minor) / float64(pow10(c.Decimals)) }

// fxKRW 는 외화 minor 를 환율 rate 로 산 원화(원 단위 반올림).
func fxKRW(c FxCurrency, minor int64, rate float64) int64 {
	return int64(math.Round(fxMajor(c, minor) * rate))
}

// fxFromKRW 는 원화 krw 로 살 수 있는 외화(최소 단위, 내림 — 원화를 넘겨 사지 않는다).
func fxFromKRW(c FxCurrency, krw int64, rate float64) int64 {
	if rate <= 0 {
		return 0
	}
	// 부동소수 오차로 딱 떨어지는 값이 하나 모자라지 않게 아주 작은 값을 더해 내린다
	return int64(math.Floor(float64(krw)/rate*float64(pow10(c.Decimals)) + 1e-6))
}


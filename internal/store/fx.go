const fxTradeCols = `id, date, currency, side, amount, krw, rate, source, plan_id, estimated, memo`

func scanFxTrade(r rowScanner) (FxTrade, error) {
	var t FxTrade
	var plan sql.NullInt64
	var est int
	err := r.Scan(&t.ID, &t.Date, &t.Currency, &t.Side, &t.Amount, &t.KRW, &t.Rate, &t.Source, &plan, &est, &t.Memo)
	t.PlanID = scanNullableID(plan)
	t.Estimated = est == 1
	return t, err
}

// ListFxTrades 는 외화 거래 전체(날짜·id 순).
func (s *Store) ListFxTrades() ([]FxTrade, error) {
	rows, err := s.query(`SELECT ` + fxTradeCols + ` FROM fx_trades ORDER BY date, id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []FxTrade{}
	for rows.Next() {
		t, err := scanFxTrade(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

// fxCheckHoldings 는 거래를 날짜순으로 쌓아 어느 시점에도 보유량보다 많이 팔지 않았는지 본다.
func fxCheckHoldings(trades []FxTrade, cur string) error {
	c, _ := FxCurrencyOf(cur)
	sort.SliceStable(trades, func(i, j int) bool {
		if trades[i].Date != trades[j].Date {
			return trades[i].Date < trades[j].Date
		}
		// 같은 날은 사기를 먼저 본다(그날 사서 그날 판 경우)
		return trades[i].Side == "buy" && trades[j].Side != "buy"
	})
	var held int64
	for _, t := range trades {
		if t.Currency != cur {
			continue
		}
		if t.Side == "buy" {
			held += t.Amount
		} else {
			held -= t.Amount
			if held < 0 {
				return fmt.Errorf("%s에 가진 %s보다 많이 팔 수 없습니다", t.Date, c.Name)
			}
		}
	}
	return nil
}

// SaveFxTrade 는 외화 거래를 추가(ID=0)하거나 고친다. 원화가 비어 있으면 외화×환율로 채운다.
// 고칠 때 환율·금액이 바뀌면 추정 표시를 끈다(실제 체결값으로 고친 것).
func (s *Store) SaveFxTrade(t FxTrade) (FxTrade, error) {
	c, ok := FxCurrencyOf(t.Currency)
	if !ok {
		return t, fmt.Errorf("모을 수 없는 통화입니다: %s", t.Currency)
	}
	if _, err := time.Parse(dateLayout, t.Date); err != nil {
		return t, fmt.Errorf("날짜는 YYYY-MM-DD 형식이어야 합니다")
	}
	if t.Side != "buy" && t.Side != "sell" {
		return t, fmt.Errorf("사기·팔기 중 하나여야 합니다")
	}
	if t.Source == "" {
		t.Source = FxManual
	}
	if t.Source == FxOpening && t.Side != "buy" {
		return t, fmt.Errorf("처음 잔고는 가진 외화로만 넣습니다")
	}
	if t.Amount <= 0 {
		return t, fmt.Errorf("외화 금액을 입력하세요")
	}
	if t.Rate <= 0 && t.KRW > 0 {
		t.Rate = float64(t.KRW) / fxMajor(c, t.Amount)
	}
	if t.Rate <= 0 {
		return t, fmt.Errorf("환율을 입력하세요")
	}
	if t.KRW <= 0 {
		t.KRW = fxKRW(c, t.Amount, t.Rate)
	}
	t.Memo = strings.TrimSpace(t.Memo)

	all, err := s.ListFxTrades()
	if err != nil {
		return t, err
	}
	var check []FxTrade
	for _, x := range all {
		if x.ID == t.ID {
			// 고침: 자동 기록의 출처·계획은 그대로 두고, 값이 바뀌면 추정 표시를 끈다
			if t.ID > 0 {
				t.Source, t.PlanID = x.Source, x.PlanID
				if x.Estimated && (x.Rate != t.Rate || x.Amount != t.Amount || x.KRW != t.KRW) {
					t.Estimated = false
				} else {
					t.Estimated = x.Estimated
				}
			}
			continue
		}
		check = append(check, x)
	}
	if err := fxCheckHoldings(append(check, t), t.Currency); err != nil {
		return t, err
	}
	// 통화를 바꾼 경우 원래 통화 쪽도 확인
	for _, x := range all {
		if x.ID == t.ID && t.ID > 0 && x.Currency != t.Currency {
			if err := fxCheckHoldings(check, x.Currency); err != nil {
				return t, err
			}
		}
	}

	args := []interface{}{t.Date, t.Currency, t.Side, t.Amount, t.KRW, t.Rate, t.Source,
		nullableID(t.PlanID), boolToInt(t.Estimated), t.Memo}
	if t.ID == 0 {
		err := s.queryRow(`INSERT INTO fx_trades(date, currency, side, amount, krw, rate, source, plan_id, estimated, memo)
VALUES(?,?,?,?,?,?,?,?,?,?) RETURNING id`, args...).Scan(&t.ID)
		return t, err
	}
	_, err = s.exec(`UPDATE fx_trades SET date=?, currency=?, side=?, amount=?, krw=?, rate=?, source=?, plan_id=?, estimated=?, memo=?
WHERE id=?`, append(args, t.ID)...)
	return t, err
}

// DeleteFxTrade 는 외화 거래를 지운다. 지우면 뒤의 팔기가 보유량을 넘는 경우는 막는다.
// 자동 기록을 지워도 그날은 다시 기록하지 않는다(계획의 last_run 이 이미 지났다).
func (s *Store) DeleteFxTrade(id int64) error {
	all, err := s.ListFxTrades()
	if err != nil {
		return err
	}
	var cur string
	var rest []FxTrade
	for _, x := range all {
		if x.ID == id {
			cur = x.Currency
			continue
		}
		rest = append(rest, x)
	}
	if cur == "" {
		return nil
	}
	if err := fxCheckHoldings(rest, cur); err != nil {
		return fmt.Errorf("이 매수를 지우면 그 뒤 팔기가 보유량을 넘습니다: %w", err)
	}
	_, err = s.exec(`DELETE FROM fx_trades WHERE id=?`, id)
	return err
}


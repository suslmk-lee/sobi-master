// planAmounts 는 계획 한 번의 매수량: (외화 최소 단위, 원화).
func planAmounts(p FxPlan, c FxCurrency, rate float64) (int64, int64) {
	if p.Unit == "fx" {
		return p.Amount, fxKRW(c, p.Amount, rate)
	}
	return fxFromKRW(c, p.Amount, rate), p.Amount
}

func isWeekend(d time.Time) bool { return d.Weekday() == time.Saturday || d.Weekday() == time.Sunday }

// planFxTrades 는 계획 p 를 from~to(양끝 포함) 동안 돌린 결과: 기록할 매수, 처리한 마지막 날, 끝났는지.
// 환율을 모르는 날에서 멈춘다(그날부터 다음에 다시 본다).
func planFxTrades(p FxPlan, from, to string, rates fxRateBook) (trades []FxTrade, lastRun string, done bool) {
	c, ok := FxCurrencyOf(p.Currency)
	if !ok {
		return nil, "", false
	}
	d, err := time.Parse(dateLayout, from)
	if err != nil {
		return nil, "", false
	}
	planID := p.ID
	for i := 0; i < 3660 && fmtDay(d) <= to; i, d = i+1, d.AddDate(0, 0, 1) {
		date := fmtDay(d)
		if p.Kind == "daily" && p.WeekdaysOnly && isWeekend(d) {
			lastRun = date
			continue
		}
		rate, _, ok := rates.on(p.Currency, date)
		if !ok {
			break
		}
		lastRun = date
		if p.Kind == "target" && rate > p.TargetRate {
			continue
		}
		amt, krw := planAmounts(p, c, rate)
		if amt <= 0 || krw <= 0 {
			continue
		}
		src := FxDaily
		if p.Kind == "target" {
			src = FxTarget
		}
		trades = append(trades, FxTrade{
			Date: date, Currency: p.Currency, Side: "buy", Amount: amt, KRW: krw, Rate: rate,
			Source: src, PlanID: &planID, Estimated: true,
		})
		if p.Kind == "target" && !p.Repeating {
			return trades, lastRun, true
		}
	}
	return trades, lastRun, false
}

// RunFxPlans 는 켜진 계획을 오늘까지 돌려 매수를 자동 기록한다. 기록한 건수를 돌려준다.
// 계획마다 (last_run 확인 → 매수 기록 → last_run 갱신)을 한 DB 트랜잭션으로 해서, 두 PC 가 같은 DB 로
// 동시에 돌아도 같은 날이 두 번 기록되지 않는다.
func (s *Store) RunFxPlans(today time.Time) (int, error) {
	todayStr := fmtDay(dayOf(today))
	plans, err := s.ListFxPlans()
	if err != nil {
		return 0, err
	}
	rates, err := s.fxRateBook()
	if err != nil {
		return 0, err
	}
	n := 0
	for _, p := range plans {
		if !p.Active || p.DoneAt != "" {
			continue
		}
		from := p.StartDate
		if p.LastRun >= from {
			d, _ := time.Parse(dateLayout, p.LastRun)
			from = fmtDay(d.AddDate(0, 0, 1))
		}
		to := todayStr
		if p.EndDate != "" && p.EndDate < to {
			to = p.EndDate
		}
		if from > to {
			continue
		}
		trades, lastRun, done := planFxTrades(p, from, to, rates)
		if lastRun == "" {
			continue
		}
		created, err := s.commitFxRun(p, trades, lastRun, done)
		if err != nil {
			return n, err
		}
		n += created
	}
	return n, nil
}

func (s *Store) commitFxRun(p FxPlan, trades []FxTrade, lastRun string, done bool) (int, error) {
	tx, err := s.db.Begin()
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	doneAt := ""
	if done {
		doneAt = lastRun
	}
	res, err := tx.Exec(pq(`UPDATE fx_plans SET last_run=?, done_at=? WHERE id=? AND last_run=? AND done_at=''`),
		lastRun, doneAt, p.ID, p.LastRun)
	if err != nil {
		return 0, err
	}
	if n, err := res.RowsAffected(); err != nil || n == 0 {
		return 0, err // 다른 곳에서 먼저 처리함
	}
	for _, t := range trades {
		if _, err := tx.Exec(pq(`INSERT INTO fx_trades(date, currency, side, amount, krw, rate, source, plan_id, estimated, memo)
VALUES(?,?,?,?,?,?,?,?,?,?)`), t.Date, t.Currency, t.Side, t.Amount, t.KRW, t.Rate, t.Source,
			nullableID(t.PlanID), boolToInt(t.Estimated), t.Memo); err != nil {
			return 0, err
		}
	}
	return len(trades), tx.Commit()
}


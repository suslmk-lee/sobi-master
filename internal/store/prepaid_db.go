func (s *Store) getPrepaidCharge(txID int64) (PrepaidCharge, error) {
	var c PrepaidCharge
	err := s.queryRow(`
SELECT pc.pass_id, pc.transaction_id, t.date, t.amount, pc.credit, t.merchant, COALESCE(p.name, '')
FROM prepaid_charges pc
JOIN transactions t ON t.id = pc.transaction_id
LEFT JOIN payment_methods p ON p.id = t.payment_method_id
WHERE pc.transaction_id=?`, txID).Scan(&c.PassID, &c.TransactionID, &c.Date, &c.Paid, &c.Credit, &c.Merchant, &c.PaymentMethodName)
	if err == sql.ErrNoRows {
		return c, ErrNotFound
	}
	return c, err
}

// AddPrepaidCharge 는 충전을 기록한다: 한 DB 트랜잭션 안에서 지출 거래를 만들고 선불권에 연결한다.
// paymentMethodID/memberID 가 0 이면 선불권 기본값을 쓴다. (분류 규칙은 학습하지 않는다)
func (s *Store) AddPrepaidCharge(passID int64, date string, amount int64, paymentMethodID, memberID int64, memo string) (PrepaidCharge, error) {
	if amount <= 0 {
		return PrepaidCharge{}, fmt.Errorf("충전 금액은 0보다 커야 합니다")
	}
	if _, err := time.Parse(dateLayout, date); err != nil {
		return PrepaidCharge{}, fmt.Errorf("날짜는 YYYY-MM-DD 형식이어야 합니다")
	}
	p, err := s.GetPrepaidPass(passID)
	if err != nil {
		if err == ErrNotFound {
			return PrepaidCharge{}, fmt.Errorf("선불권을 찾을 수 없습니다")
		}
		return PrepaidCharge{}, err
	}
	t := Transaction{
		Date: date, Amount: amount, Direction: "expense", Merchant: p.Merchant, Memo: memo,
		CategoryID: p.CategoryID, PaymentMethodID: p.PaymentMethodID, MemberID: p.MemberID, Source: "manual",
	}
	if t.Merchant == "" {
		t.Merchant = p.Name
	}
	if paymentMethodID > 0 {
		t.PaymentMethodID = &paymentMethodID
	}
	if memberID > 0 {
		t.MemberID = &memberID
	}
	tx, err := s.db.Begin()
	if err != nil {
		return PrepaidCharge{}, err
	}
	defer tx.Rollback()
	var txID int64
	if err := tx.QueryRow(pq(insertTxSQL), insertTxArgs(t)...).Scan(&txID); err != nil {
		return PrepaidCharge{}, err
	}
	if _, err := tx.Exec(pq(`INSERT INTO prepaid_charges(transaction_id, pass_id, credit) VALUES(?,?,?)`),
		txID, passID, prepaidCredit(p.DiscountMode, p.BonusBp, amount)); err != nil {
		return PrepaidCharge{}, err
	}
	if err := tx.Commit(); err != nil {
		return PrepaidCharge{}, err
	}
	return s.getPrepaidCharge(txID)
}

// LinkPrepaidCharge 는 이미 있는 지출 거래를 선불권 충전으로 연결한다.
func (s *Store) LinkPrepaidCharge(passID, txID int64) (PrepaidCharge, error) {
	p, err := s.GetPrepaidPass(passID)
	if err != nil {
		if err == ErrNotFound {
			return PrepaidCharge{}, fmt.Errorf("선불권을 찾을 수 없습니다")
		}
		return PrepaidCharge{}, err
	}
	var direction string
	var amount int64
	if err := s.queryRow(`SELECT direction, amount FROM transactions WHERE id=?`, txID).Scan(&direction, &amount); err != nil {
		if err == sql.ErrNoRows {
			return PrepaidCharge{}, fmt.Errorf("거래를 찾을 수 없습니다")
		}
		return PrepaidCharge{}, err
	}
	if direction != "expense" {
		return PrepaidCharge{}, fmt.Errorf("지출 거래만 충전으로 연결할 수 있습니다")
	}
	var existing int64
	err = s.queryRow(`SELECT pass_id FROM prepaid_charges WHERE transaction_id=?`, txID).Scan(&existing)
	if err == nil {
		if existing == passID {
			return s.getPrepaidCharge(txID) // 이미 이 선불권에 연결됨 — 그대로
		}
		return PrepaidCharge{}, fmt.Errorf("이미 다른 선불권에 연결된 거래입니다")
	} else if err != sql.ErrNoRows {
		return PrepaidCharge{}, err
	}
	if _, err := s.exec(`INSERT INTO prepaid_charges(transaction_id, pass_id, credit) VALUES(?,?,?)`,
		txID, passID, prepaidCredit(p.DiscountMode, p.BonusBp, amount)); err != nil {
		return PrepaidCharge{}, err
	}
	return s.getPrepaidCharge(txID)
}

// UnlinkPrepaidCharge 는 충전 연결을 끊는다(거래는 지출로 남는다).
func (s *Store) UnlinkPrepaidCharge(txID int64) error {
	_, err := s.exec(`DELETE FROM prepaid_charges WHERE transaction_id=?`, txID)
	return err
}


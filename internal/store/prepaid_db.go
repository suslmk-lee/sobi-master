// SavePrepaidUse 는 사용 기록을 검증해 저장한다(ID 0 이면 새로). Deducted 가 0 이고 정가가 있으면
// 선불권의 할인 방식으로 차감액을 계산한다.
func (s *Store) SavePrepaidUse(u PrepaidUse) (PrepaidUse, error) {
	p, err := s.GetPrepaidPass(u.PassID)
	if err != nil {
		if err == ErrNotFound {
			return u, fmt.Errorf("선불권을 찾을 수 없습니다")
		}
		return u, err
	}
	if _, err := time.Parse(dateLayout, u.Date); err != nil {
		return u, fmt.Errorf("날짜는 YYYY-MM-DD 형식이어야 합니다")
	}
	if u.ListPrice < 0 || u.Deducted < 0 {
		return u, fmt.Errorf("금액은 0 이상이어야 합니다")
	}
	if u.Deducted == 0 && u.ListPrice > 0 {
		u.Deducted = prepaidDeduct(p.DiscountMode, p.DiscountBp, u.ListPrice)
	}
	if u.ID == 0 {
		err = s.queryRow(`
INSERT INTO prepaid_uses(pass_id, date, list_price, deducted, member_id, memo) VALUES(?,?,?,?,?,?) RETURNING id`,
			u.PassID, u.Date, u.ListPrice, u.Deducted, nullableID(u.MemberID), u.Memo).Scan(&u.ID)
		return u, err
	}
	res, err := s.exec(`
UPDATE prepaid_uses SET date=?, list_price=?, deducted=?, member_id=?, memo=? WHERE id=? AND pass_id=?`,
		u.Date, u.ListPrice, u.Deducted, nullableID(u.MemberID), u.Memo, u.ID, u.PassID)
	if err != nil {
		return u, err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return u, ErrNotFound
	}
	return u, nil
}

// DeletePrepaidUse 는 사용 기록 하나를 지운다.
func (s *Store) DeletePrepaidUse(id int64) error {
	_, err := s.exec(`DELETE FROM prepaid_uses WHERE id=?`, id)
	return err
}

// GetPrepaidHistory 는 선불권 한 장의 충전·사용 내역(최근순).
func (s *Store) GetPrepaidHistory(passID int64) (PrepaidHistory, error) {
	h := PrepaidHistory{Charges: []PrepaidCharge{}, Uses: []PrepaidUse{}}
	rows, err := s.query(`
SELECT pc.pass_id, pc.transaction_id, t.date, t.amount, pc.credit, t.merchant, COALESCE(p.name, '')
FROM prepaid_charges pc
JOIN transactions t ON t.id = pc.transaction_id
LEFT JOIN payment_methods p ON p.id = t.payment_method_id
WHERE pc.pass_id=?
ORDER BY t.date DESC, t.id DESC`, passID)
	if err != nil {
		return h, err
	}
	for rows.Next() {
		var c PrepaidCharge
		if err := rows.Scan(&c.PassID, &c.TransactionID, &c.Date, &c.Paid, &c.Credit, &c.Merchant, &c.PaymentMethodName); err != nil {
			rows.Close()
			return h, err
		}
		h.Charges = append(h.Charges, c)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return h, err
	}
	rows.Close()

	urows, err := s.query(`
SELECT u.id, u.pass_id, u.date, u.list_price, u.deducted, u.member_id, COALESCE(m.name, ''), u.memo
FROM prepaid_uses u LEFT JOIN members m ON m.id = u.member_id
WHERE u.pass_id=?
ORDER BY u.date DESC, u.id DESC`, passID)
	if err != nil {
		return h, err
	}
	defer urows.Close()
	for urows.Next() {
		var u PrepaidUse
		var mid sql.NullInt64
		if err := urows.Scan(&u.ID, &u.PassID, &u.Date, &u.ListPrice, &u.Deducted, &mid, &u.MemberName, &u.Memo); err != nil {
			return h, err
		}
		u.MemberID = scanNullableID(mid)
		h.Uses = append(h.Uses, u)
	}
	return h, urows.Err()
}

// prepaidSchema 는 선불권 테이블(migrate 에서 본 스키마 뒤에 이어 실행).
// 충전 = 지출 거래 한 건에 연결(prepaid_charges), 차감(prepaid_uses)은 거래가 아니다.
// 선불권을 지우면 연결(prepaid_charges)만 사라지고 거래는 평범한 지출로 남는다.
const prepaidSchema = `
CREATE TABLE IF NOT EXISTS prepaid_passes (
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name              TEXT NOT NULL,
	merchant          TEXT NOT NULL DEFAULT '',
	discount_mode     TEXT NOT NULL DEFAULT 'none',
	bonus_bp          INTEGER NOT NULL DEFAULT 0,
	discount_bp       INTEGER NOT NULL DEFAULT 0,
	opening_balance   BIGINT NOT NULL DEFAULT 0,
	opening_date      TEXT NOT NULL DEFAULT '',
	expires_at        TEXT NOT NULL DEFAULT '',
	category_id       BIGINT REFERENCES categories(id) ON DELETE SET NULL,
	payment_method_id BIGINT REFERENCES payment_methods(id) ON DELETE SET NULL,
	member_id         BIGINT REFERENCES members(id) ON DELETE SET NULL,
	memo              TEXT NOT NULL DEFAULT '',
	active            INTEGER NOT NULL DEFAULT 1,
	created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS prepaid_charges (
	transaction_id BIGINT PRIMARY KEY REFERENCES transactions(id) ON DELETE CASCADE,
	pass_id        BIGINT NOT NULL REFERENCES prepaid_passes(id) ON DELETE CASCADE,
	credit         BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prepaid_charges_pass ON prepaid_charges(pass_id);
CREATE TABLE IF NOT EXISTS prepaid_uses (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	pass_id    BIGINT NOT NULL REFERENCES prepaid_passes(id) ON DELETE CASCADE,
	date       TEXT NOT NULL,
	list_price BIGINT NOT NULL DEFAULT 0,
	deducted   BIGINT NOT NULL DEFAULT 0,
	member_id  BIGINT REFERENCES members(id) ON DELETE SET NULL,
	memo       TEXT NOT NULL DEFAULT '',
	created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_prepaid_uses_pass ON prepaid_uses(pass_id);
`

// ---- 순수 계산 ----

// roundDiv 는 n/d 를 반올림(0.5 올림, 음수는 0에서 멀어지는 쪽)한 정수로.
func roundDiv(n, d int64) int64 {
	if d == 0 {
		return 0
	}
	if n >= 0 {
		return (n + d/2) / d
	}
	return -((-n + d/2) / d)
}

// prepaidCredit 는 결제액 paid 로 적립되는 금액. bonus 면 paid + paid×bp/10000, 그 외는 paid.
func prepaidCredit(mode string, bonusBp int, paid int64) int64 {
	if mode == "bonus" {
		return paid + roundDiv(paid*int64(bonusBp), 10000)
	}
	return paid
}

// prepaidDeduct 는 정가 list 를 쓸 때 차감되는 금액. discount 면 정가 × (1 − bp/10000), 그 외는 정가.
func prepaidDeduct(mode string, discountBp int, list int64) int64 {
	if mode == "discount" {
		return roundDiv(list*int64(10000-discountBp), 10000)
	}
	return list
}

func normalizePrepaidMode(m string) string {
	switch m {
	case "bonus", "discount":
		return m
	}
	return "none"
}

func validDateOrEmpty(s string) bool {
	if s == "" {
		return true
	}
	_, err := time.Parse(dateLayout, s)
	return err == nil
}

// prepaidUsage 는 사용 내역(순서 무관)에서 마지막 사용일·최근 평균 차감액·평균 간격을 구한다.
// 평균 차감액은 최근 5회, 평균 간격(일)은 최근 6회 기준이며 2회 미만이면 간격은 0.
func prepaidUsage(uses []PrepaidUse) (lastUse string, avgAmount int64, avgDays int) {
	if len(uses) == 0 {
		return "", 0, 0
	}
	s := append([]PrepaidUse(nil), uses...)
	sort.SliceStable(s, func(i, j int) bool {
		if s[i].Date != s[j].Date {
			return s[i].Date > s[j].Date
		}
		return s[i].ID > s[j].ID
	})
	lastUse = s[0].Date
	n := len(s)
	if n > 5 {
		n = 5
	}
	var sum int64
	for _, u := range s[:n] {
		sum += u.Deducted
	}
	avgAmount = roundDiv(sum, int64(n))
	m := len(s)
	if m > 6 {
		m = 6
	}
	if m >= 2 {
		newest, e1 := time.Parse(dateLayout, s[0].Date)
		oldest, e2 := time.Parse(dateLayout, s[m-1].Date)
		if e1 == nil && e2 == nil {
			days := int64(newest.Sub(oldest).Hours() / 24)
			avgDays = int(roundDiv(days, int64(m-1)))
		}
	}
	return lastUse, avgAmount, avgDays
}

// prepaidChargeRow 는 상태 계산에 쓰는 충전 한 건(거래 날짜·결제액 + 적립액).
type prepaidChargeRow struct {
	Date   string
	Paid   int64
	Credit int64
}

// buildPrepaidStatus 는 선불권 한 장의 잔액·절약액·소진 예상을 계산한다(순수 함수).
func buildPrepaidStatus(p PrepaidPass, charges []prepaidChargeRow, uses []PrepaidUse, today time.Time) PrepaidStatus {
	st := PrepaidStatus{Pass: p}
	inWindow := func(d string) bool { return p.OpeningDate == "" || d >= p.OpeningDate }
	var used []PrepaidUse
	for _, c := range charges {
		if !inWindow(c.Date) {
			continue
		}
		st.ChargeCount++
		st.TotalPaid += c.Paid
		st.TotalCredit += c.Credit
		if c.Credit > c.Paid {
			st.Saved += c.Credit - c.Paid
		}
	}
	for _, u := range uses {
		if !inWindow(u.Date) {
			continue
		}
		used = append(used, u)
		st.UseCount++
		st.TotalUsed += u.Deducted
		if u.ListPrice > u.Deducted {
			st.Saved += u.ListPrice - u.Deducted
		}
	}
	st.Balance = p.OpeningBalance + st.TotalCredit - st.TotalUsed
	st.LastUse, st.AvgUseAmount, st.AvgUseDays = prepaidUsage(used)
	if st.AvgUseAmount > 0 {
		if st.Balance > 0 {
			st.UsesLeft = int(st.Balance / st.AvgUseAmount)
		}
		st.Low = st.Balance < st.AvgUseAmount
		if st.AvgUseDays > 0 && st.LastUse != "" {
			if lu, err := time.Parse(dateLayout, st.LastUse); err == nil {
				st.RunOutDate = lu.AddDate(0, 0, st.UsesLeft*st.AvgUseDays).Format(dateLayout)
			}
		}
	}
	if p.ExpiresAt != "" && today.Format(dateLayout) > p.ExpiresAt {
		st.Expired = true
	}
	return st
}


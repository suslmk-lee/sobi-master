const prepaidPassCols = `id, name, merchant, discount_mode, bonus_bp, discount_bp, opening_balance, opening_date, expires_at, category_id, payment_method_id, member_id, memo, active`

type rowScanner interface {
	Scan(dest ...interface{}) error
}

func scanPrepaidPass(r rowScanner) (PrepaidPass, error) {
	var p PrepaidPass
	var cid, pid, mid sql.NullInt64
	var active int
	err := r.Scan(&p.ID, &p.Name, &p.Merchant, &p.DiscountMode, &p.BonusBp, &p.DiscountBp, &p.OpeningBalance,
		&p.OpeningDate, &p.ExpiresAt, &cid, &pid, &mid, &p.Memo, &active)
	p.CategoryID, p.PaymentMethodID, p.MemberID = scanNullableID(cid), scanNullableID(pid), scanNullableID(mid)
	p.Active = active == 1
	return p, err
}

// GetPrepaidPass 는 선불권 한 장. 없으면 ErrNotFound.
func (s *Store) GetPrepaidPass(id int64) (PrepaidPass, error) {
	p, err := scanPrepaidPass(s.queryRow(`SELECT `+prepaidPassCols+` FROM prepaid_passes WHERE id=?`, id))
	if err == sql.ErrNoRows {
		return p, ErrNotFound
	}
	return p, err
}

// SavePrepaidPass 는 선불권을 검증해 저장하고(ID 0 이면 새로) 저장된 행을 돌려준다.
func (s *Store) SavePrepaidPass(p PrepaidPass) (PrepaidPass, error) {
	p.Name = strings.TrimSpace(p.Name)
	p.Merchant = strings.TrimSpace(p.Merchant)
	if p.Name == "" {
		return p, fmt.Errorf("선불권 이름을 입력하세요")
	}
	p.DiscountMode = normalizePrepaidMode(p.DiscountMode)
	if p.BonusBp < 0 || p.BonusBp > 10000 || p.DiscountBp < 0 || p.DiscountBp > 10000 {
		return p, fmt.Errorf("할인율은 0~100%% 사이여야 합니다")
	}
	if !validDateOrEmpty(p.OpeningDate) || !validDateOrEmpty(p.ExpiresAt) {
		return p, fmt.Errorf("날짜는 YYYY-MM-DD 형식이어야 합니다")
	}
	args := []interface{}{p.Name, p.Merchant, p.DiscountMode, p.BonusBp, p.DiscountBp, p.OpeningBalance,
		p.OpeningDate, p.ExpiresAt, nullableID(p.CategoryID), nullableID(p.PaymentMethodID), nullableID(p.MemberID),
		p.Memo, boolToInt(p.Active)}
	if p.ID == 0 {
		err := s.queryRow(`
INSERT INTO prepaid_passes(name, merchant, discount_mode, bonus_bp, discount_bp, opening_balance, opening_date, expires_at, category_id, payment_method_id, member_id, memo, active)
VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id`, args...).Scan(&p.ID)
		return p, err
	}
	res, err := s.exec(`
UPDATE prepaid_passes SET name=?, merchant=?, discount_mode=?, bonus_bp=?, discount_bp=?, opening_balance=?, opening_date=?, expires_at=?, category_id=?, payment_method_id=?, member_id=?, memo=?, active=?
WHERE id=?`, append(args, p.ID)...)
	if err != nil {
		return p, err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return p, ErrNotFound
	}
	return p, nil
}

// DeletePrepaidPass 는 선불권과 그 사용 기록·충전 연결을 지운다. 충전 거래는 평범한 지출로 남는다.
func (s *Store) DeletePrepaidPass(id int64) error {
	_, err := s.exec(`DELETE FROM prepaid_passes WHERE id=?`, id)
	return err
}

// ListPrepaidStatuses 는 선불권 목록(사용 중 먼저, 이름순)과 잔액·절약액·소진 예상.
func (s *Store) ListPrepaidStatuses(today time.Time) ([]PrepaidStatus, error) {
	rows, err := s.query(`SELECT ` + prepaidPassCols + ` FROM prepaid_passes ORDER BY active DESC, name, id`)
	if err != nil {
		return nil, err
	}
	var passes []PrepaidPass
	for rows.Next() {
		p, err := scanPrepaidPass(rows)
		if err != nil {
			rows.Close()
			return nil, err
		}
		passes = append(passes, p)
	}
	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, err
	}
	rows.Close()

	charges := map[int64][]prepaidChargeRow{}
	crows, err := s.query(`SELECT pc.pass_id, t.date, t.amount, pc.credit FROM prepaid_charges pc JOIN transactions t ON t.id = pc.transaction_id`)
	if err != nil {
		return nil, err
	}
	for crows.Next() {
		var pid int64
		var c prepaidChargeRow
		if err := crows.Scan(&pid, &c.Date, &c.Paid, &c.Credit); err != nil {
			crows.Close()
			return nil, err
		}
		charges[pid] = append(charges[pid], c)
	}
	if err := crows.Err(); err != nil {
		crows.Close()
		return nil, err
	}
	crows.Close()

	uses := map[int64][]PrepaidUse{}
	urows, err := s.query(`SELECT id, pass_id, date, list_price, deducted FROM prepaid_uses`)
	if err != nil {
		return nil, err
	}
	for urows.Next() {
		var u PrepaidUse
		if err := urows.Scan(&u.ID, &u.PassID, &u.Date, &u.ListPrice, &u.Deducted); err != nil {
			urows.Close()
			return nil, err
		}
		uses[u.PassID] = append(uses[u.PassID], u)
	}
	if err := urows.Err(); err != nil {
		urows.Close()
		return nil, err
	}
	urows.Close()

	out := make([]PrepaidStatus, 0, len(passes))
	for _, p := range passes {
		out = append(out, buildPrepaidStatus(p, charges[p.ID], uses[p.ID], today))
	}
	return out, nil
}


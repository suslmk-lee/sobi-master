// Open 은 config.json 의 Supabase 연결 문자열로 접속한다.
// 서버에 데이터가 하나도 없고 이전 버전의 로컬 SQLite 파일(sobi.db)이 있으면
// 그 데이터를 자동으로 Supabase 로 옮긴 뒤 시작한다.
func Open() (*Store, error) {
	cfg, err := LoadConfig()
	if err != nil {
		return nil, err
	}
	legacy, lerr := LegacySQLitePath()
	if lerr != nil {
		legacy = ""
	}
	return openReady(cfg.DatabaseURL, legacy)
}

// OpenURL 은 설정 파일 없이 연결 문자열로 접속해 Open 과 같은 준비(시드·계층 정리)를 한다.
// 로컬 SQLite 이전은 하지 않는다. (모바일 API 서버용)
func OpenURL(dsn string) (*Store, error) {
	return openReady(dsn, "")
}

// openReady 는 접속 → (비었으면) legacy SQLite 이전 또는 기본값 시드 → 정리 작업까지 한다.
//
// 스키마가 그대로고 데이터도 있으면(평소 시작) 기본 결제수단 보충·카테고리 정리는 뒤에서 한다 —
// 둘 다 여러 번 해도 같은 결과라 첫 화면을 기다리게 할 이유가 없다. 첫 화면이 동시에 여러 조회를
// 보낼 연결도 접속하자마자 뒤에서 미리 맺어 둔다(Warm).
func openReady(dsn, legacy string) (*Store, error) {
	s, needSetup, err := openSchema(dsn)
	if err != nil {
		return nil, err
	}
	go s.Warm(context.Background(), WarmConns)
	if !needSetup {
		go func() {
			if err := s.tidyUp(); err != nil {
				log.Printf("시작 정리 작업: %v", err)
			}
		}()
		return s, nil
	}

	empty, err := s.isEmpty()
	if err != nil {
		s.Close()
		return nil, err
	}
	if empty {
		if legacy != "" {
			if _, statErr := os.Stat(legacy); statErr == nil {
				if merr := s.migrateFromSQLite(legacy); merr != nil {
					s.Close()
					return nil, fmt.Errorf("로컬 데이터를 Supabase 로 옮기는 중 오류: %w", merr)
				}
				empty = false
			}
		}
	}
	if empty {
		if err := s.seedDefaults(); err != nil {
			s.Close()
			return nil, err
		}
	}
	if err := s.tidyUp(); err != nil {
		s.Close()
		return nil, err
	}
	return s, nil
}

// tidyUp 은 시작 때마다 하는 정리: 빠진 기본 결제수단을 보충하고, "식비/배달" 처럼 슬래시로 계층을
// 흉내낸 이름을 주/부 계층으로 나눈다. 여러 번 해도 결과가 같다.
func (s *Store) tidyUp() error {
	if err := s.seedPaymentMethods(); err != nil {
		return err
	}
	return s.splitSlashCategories()
}

// OpenAt 은 Postgres 연결 문자열로 접속하고 스키마만 준비한다. (시드 없음)
func OpenAt(dsn string) (*Store, error) {
	s, _, err := openSchema(dsn)
	return s, err
}

// openSchema 는 접속하고 스키마를 준비한다. 지문이 같으면 스키마 적용을 건너뛴다.
// needSetup 은 스키마를 이번에 (다시) 적용했거나 데이터가 비어 있다는 뜻 — 시드·정리를 바로 해야 한다.
func openSchema(dsn string) (s *Store, needSetup bool, err error) {
	db, err := sql.Open("pgx", normalizeDSN(dsn))
	if err != nil {
		return nil, false, err
	}
	configurePool(db)
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		db.Close()
		return nil, false, fmt.Errorf("Supabase 접속 실패: %w", err)
	}
	s = &Store{db: db}
	stamp, hasData, serr := s.schemaState()
	if serr == nil && stamp == schemaStamp {
		return s, !hasData, nil
	}
	if err := s.migrate(); err != nil {
		db.Close()
		return nil, false, err
	}
	return s, true, nil
}

// 연결 풀. Supabase 는 멀리(싱가포르) 있어 새 연결(TCP+TLS+인증)마다 수백 ms 가 든다.
// database/sql 기본값은 쉬는 연결을 2개만 남겨, 화면이 API 를 동시에 부르거나 한 API 가 조회를
// 동시에 돌리면 매번 새로 연결했다. 쉬는 연결을 넉넉히 남겨 다시 쓴다.
// 동시 연결 수(MaxOpenConns)는 일부러 묶지 않는다 — 행을 읽는 도중 다른 조회를 하는 코드가 있으면
// 상한에 걸린 고루틴들이 서로 연결을 기다리며 멈출 수 있다.
//
// 대시보드 한 번에 조회가 30개 가까이 동시에 나가므로 쉬는 연결을 32개까지 남긴다. Supabase 풀러의
// 트랜잭션 모드(6543)는 앱 쪽 연결을 서버 연결과 따로 세어 넉넉히 받으므로 서버에 부담이 되지 않는다.
const (
	poolMaxIdle     = 32
	poolMaxIdleTime = 10 * time.Minute
	poolMaxLifetime = 30 * time.Minute
)

// WarmConns 는 미리 맺어 두고 살려 두는 연결 수(첫 화면이 동시에 여러 조회를 보낼 때 쓴다).
const WarmConns = 16

// Warm 은 연결을 n 개 확보해 하나씩 확인(ping)하고 풀에 돌려준다. 쉬던 연결은 확인만 하고,
// 모자라면 새로 맺고, 끊어진 연결은 버린다(다음에 새로 맺는다). 오류는 무시한다 — 미리 해 두는 일일 뿐이다.
func (s *Store) Warm(ctx context.Context, n int) {
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	conns := make([]*sql.Conn, n)
	var wg sync.WaitGroup
	wg.Add(n)
	for i := range conns {
		go func() {
			defer wg.Done()
			c, err := s.db.Conn(ctx)
			if err != nil {
				return
			}
			if err := c.PingContext(ctx); err != nil {
				c.Close()
				return
			}
			conns[i] = c
		}()
	}
	wg.Wait()
	for _, c := range conns {
		if c != nil {
			c.Close() // 풀로 돌려준다
		}
	}
}

func configurePool(db *sql.DB) {
	db.SetMaxIdleConns(poolMaxIdle)
	db.SetConnMaxIdleTime(poolMaxIdleTime)
	db.SetConnMaxLifetime(poolMaxLifetime)
}

func (s *Store) Close() error { return s.db.Close() }

